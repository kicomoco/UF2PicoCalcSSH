"""Generate src/ca_roots.c (DER trust anchors for HTTPS update checks) from a Mozilla PEM bundle.

Usage: curl -o cacert.pem https://curl.se/ca/cacert.pem
       python3 tools/gen_ca_roots.py cacert.pem > src/ca_roots.c
"""
import base64
import re
import sys

# github.com chains to USERTrust/Sectigo; release assets on githubusercontent.com to ISRG.
# DigiCert roots cover GitHub's previous CA in case it changes back.
ROOTS = [
    "ISRG Root X1", "ISRG Root X2",
    "USERTrust ECC Certification Authority", "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46", "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2", "DigiCert Global Root G3",
]

text = open(sys.argv[1], encoding="utf-8").read()
found = {}
for name, body in re.findall(r"\n([^\n#][^\n]*)\n=+\n(?:#[^\n]*\n)*-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----", text, re.S):
    if name in ROOTS:
        found[name] = base64.b64decode("".join(body.split()))
missing = [n for n in ROOTS if n not in found]
if missing:
    sys.exit(f"Missing roots: {missing}")
print("/* Generated by tools/gen_ca_roots.py from the Mozilla CA bundle; do not edit. */")
print('#include "ca_roots.h"\n')
for i, name in enumerate(ROOTS):
    der = found[name]
    print(f"/* {name} */")
    print(f"static const unsigned char root{i}[{len(der)}] = {{")
    for j in range(0, len(der), 16):
        print("    " + ", ".join(f"0x{b:02x}" for b in der[j:j + 16]) + ",")
    print("};")
print("\nconst ca_root_t ca_roots[] = {")
for i, name in enumerate(ROOTS):
    print(f'    {{"{name}", root{i}, sizeof(root{i})}},')
print("};")
print("const unsigned ca_root_count = sizeof(ca_roots) / sizeof(ca_roots[0]);")
